    static constexpr uint8_t PAT_CH_MAX = 3;
    static const uint8_t pat[PAT_CH_MAX][PATTERN_MAX][64];
    int8_t patIndex[PAT_CH_MAX] = {0};

    void addIndex(uint8_t ch, int8_t delta)
    {
        patIndex[ch] = constrain(patIndex[ch] + delta, 0, PATTERN_MAX - 1);
    }

    const uint8_t* getPattern(uint8_t ch) { return pat[ch][patIndex[ch]]; }
